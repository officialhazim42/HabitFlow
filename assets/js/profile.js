/**
 * Attaches modal events
 */
function attachModalListeners() {
  if (!modalElement) return;

  const closeBtn = document.getElementById('closeDevModalBtn');
  if (closeBtn) closeBtn.addEventListener('click', closeDeveloperModal);

  modalElement.addEventListener('click', (e) => {
    if (e.target === modalElement) closeDeveloperModal();
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modalElement.classList.contains('is-open')) {
      closeDeveloperModal();
    }
  });

  // Copy Email interaction
  const copyEmailBtn = document.getElementById('copyDevEmailBtn');
  if (copyEmailBtn) {
    copyEmailBtn.addEventListener('click', async () => {
      await copyToClipboard(DEVELOPER_INFO.email, 'Email copied to clipboard');
    });
  }

  // Discord interaction: copies username and opens link
  const discordBtn = modalElement.querySelector('[data-is-discord="true"]');
  if (discordBtn) {
    discordBtn.addEventListener('click', async () => {
      await copyToClipboard('officialhazim42', 'Copied Discord username: officialhazim42');
    });
  }
}

/**
 * Generic clipboard copy with graceful fallback
 */
export async function copyToClipboard(text, successMessage = 'Copied to clipboard') {
  let copied = false;
  if (navigator.clipboard && navigator.clipboard.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      copied = true;
    } catch (err) {
      console.warn('Clipboard writeText failed', err);
    }
  }

  if (!copied) {
    try {
      const textarea = document.createElement('textarea');
      textarea.value = text;
      textarea.style.position = 'fixed';
      textarea.style.opacity = '0';
      document.body.appendChild(textarea);
      textarea.select();
      copied = document.execCommand('copy');
      document.body.removeChild(textarea);
    } catch (e) {
      console.error('execCommand copy failed', e);
    }
  }

  if (copied) {
    showToast(successMessage, 'success');
  } else {
    window.prompt('Copy to clipboard: Ctrl+C, Enter', text);
  }
}

/**
 * Open developer modal
 */
export function openDeveloperModal() {
  mountDeveloperModal();
  if (!modalElement) return;

  lastFocusedElement = document.activeElement;
  modalElement.classList.add('is-open');
  document.body.style.overflow = 'hidden';

  const closeBtn = document.getElementById('closeDevModalBtn');
  if (closeBtn) closeBtn.focus();
}

/**
 * Close developer modal
 */
export function closeDeveloperModal() {
  if (!modalElement) return;

  modalElement.classList.remove('is-open');
  document.body.style.overflow = '';

  if (lastFocusedElement && typeof lastFocusedElement.focus === 'function') {
    lastFocusedElement.focus();
  }
}

/**
 * Accessible Toast notification with Lucide icons (No emojis)
 */
export function showToast(message, type = 'info', duration = 3500) {
  let container = document.getElementById('habitflowToastContainer');
  if (!container) {
    container = document.createElement('div');
    container.id = 'habitflowToastContainer';
    container.className = 'toast-container';
    container.setAttribute('aria-live', 'polite');
    container.setAttribute('aria-atomic', 'true');
    document.body.appendChild(container);
  }

  const iconMap = {
    success: ICONS.check,
    error: ICONS.alertCircle,
    info: ICONS.info
  };

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  toast.innerHTML = `
    <span class="toast-icon">${iconMap[type] || ICONS.info}</span>
    <div class="toast-body">${message}</div>
    <button class="toast-close" aria-label="Dismiss">${ICONS.close}</button>
  `;

  const closeToast = () => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateY(8px)';
    setTimeout(() => {
      if (toast.parentElement) toast.parentElement.removeChild(toast);
    }, 200);
  };

  toast.querySelector('.toast-close').addEventListener('click', closeToast);
  container.appendChild(toast);

  if (duration > 0) {
    setTimeout(closeToast, duration);
  }
}

document.addEventListener('click', (e) => {
  const trigger = e.target.closest('[data-open-developer-modal]');
  if (trigger) {
    e.preventDefault();
    openDeveloperModal();
  }
});
